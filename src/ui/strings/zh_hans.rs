fn write(a: Arg<'_>, out: &mut dyn fmt::Write) -> fmt::Result {
    match a {
        Arg::MoveToWindow(n) => write!(out, "移到窗口 {n}"),
        Arg::PaneCount { cols, rows } => write!(out, "{cols} × {rows} = {} 个窗格", cols * rows),
        Arg::ProcessDetail { pane, sid, shell_pid } => {
            write!(out, "{pane} · sid {sid} · Shell pid {shell_pid}")
        }
        Arg::ResetAt(at) => write!(out, "重置：{at}"),
        Arg::UpdatedAt(at) => write!(out, "更新于 {at}"),
        Arg::SessionStarting(id) => write!(out, "会话 {id} 正在启动…"),
        Arg::SessionUnavailable(id) => write!(out, "会话 {id} 不可用，按任意键重试"),
        Arg::ProfileRow { n, current: true } => write!(out, "● 账户 {n}"),
        Arg::ProfileRow { n, current: false } => write!(out, "   账户 {n}"),
        Arg::HandOffTo(target) => write!(out, "交接给 {target}"),
        Arg::SwitchToProfile(n) => write!(out, "切换到 P{n}"),
        Arg::Helpers(n) => write!(out, "帮手 {n}"),
        Arg::HelpersOf(n) => write!(out, "帮手（{n}）…"),
        Arg::ChildOf(code) => write!(out, "（#{code:04} 的子窗格）"),
        Arg::MoreChildren(n) => write!(out, "…另外 {n} 个"),
        Arg::WindowFull(n) => write!(out, "这个窗口已经有 {n} 个窗格，放不下更多了"),
        Arg::RanFor { minutes: m @ 0..60 } => write!(out, "{m} 分"),
        Arg::RanFor { minutes: m } => write!(out, "{} 小时 {} 分", m / 60, m % 60),
        Arg::ModelPutBack { to, back } => write!(out, "所有账号共用的 Claude Code 默认模型未经确认被改成了 {to}，已改回 {back}"),
        Arg::ModelNowIs(to) => write!(out, "所有账号共用的 Claude Code 默认模型现在是 {to}"),
        Arg::WebOpening(url) => write!(out, "正在打开 {url}…"),
        Arg::WebPageRow(url) => write!(out, "网页 {url}"),
        Arg::WebOpenRow(url) => write!(out, "打开网页 {url}"),
        Arg::WebPasteCut(mb) => write!(out, "只有剪贴板里的前 {mb} MB 粘贴进了网页"),
        Arg::WebVersion { side, theirs: Some((a, b)), ours: (c, d) } => {
            write!(out, "madcawl 的 {side} 支持版本 {a}–{b}，marspot 支持 {c}–{d}")
        }
        Arg::WebVersion { side, theirs: None, ours: (c, d) } => {
            write!(out, "madcawl 的 {side} 比 marspot 支持的版本 {c}–{d} 旧")
        }
        Arg::WebFailed(why) => write!(out, "无法显示页面：{why}"),
        Arg::InstallAsk { cli, place, megabytes } => write!(
            out,
            "要把 {cli} 安装到 {place} 吗？从发行方下载，约占 {megabytes} MB。按 Ctrl-Option-Y 安装，按 Ctrl-Option-N 以后不装也不更新；其他键照常发给窗格"
        ),
    }
}
