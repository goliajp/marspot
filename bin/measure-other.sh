#!/usr/bin/env bash
# Cross-terminal companion to bin/measure.sh.
#
# AppleScript-driven launching of iTerm2 / Warp / Terminal.app is too
# fragile for benching (AppleEvent timeouts, profile-specific shell
# init, smart-paste rewriting commands, alias expansion of `cat`).
#
# Pragmatic alternative: print a single command line per terminal.
# Open the target terminal, paste, hit return.  The line runs all four
# `cat-*` scenarios with `/usr/bin/time -p /bin/cat` and writes to a
# known marker.  This script polls for that marker, parses the timings,
# and prints a comparison table.
#
# Usage:
#   bin/measure-other.sh
#     -> prints commands, waits for markers (Ctrl-C to abort)
#   bin/measure-other.sh --print-only
#     -> just print, don't wait

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCENARIOS_DIR="$ROOT/bench/scenarios"
RESULTS_DIR="$ROOT/bench/results"
# LIVE_MIN_BYTES / live_repeat / live_cat_args — the same live-sizing
# rule bin/measure.sh applies to marspot, so both sides of the
# comparison push the same number of bytes.
source "$ROOT/bin/_lib.sh"
mkdir -p "$RESULTS_DIR"

# This measurement saturates the machine it runs on: it pushes 32 MB
# into each terminal, four scenarios, three trials.  On the dev box
# that means disturbing whatever the user is doing AND contaminating
# the numbers — run on the studio 2026-09-07 with nine live panes, the
# marspot cat-ascii trials came back 380 / 1710 / 1890 ms and the
# median took a disturbed one, producing a "0.21x vs best other" that
# was pure interference.
#
# The bench host is mini (see .claude/rules/perf-attack.md).  Driving
# GUI terminals needs a GUI session, which ssh does not have, so the
# route is `bin/remote-measure-others.sh` — it health-checks for
# exactly that and prints the Screen-Sharing steps.
#
# Set MARSPOT_MEASURE_ANYWHERE=1 to override, deliberately.
if [[ -z "${MARSPOT_MEASURE_ANYWHERE:-}" && "$(hostname -s)" != "mini" ]]; then
  cat >&2 <<'WARN'
This saturates the machine it runs on, and this is not the bench host.

  * numbers taken here are contaminated by whatever else is running
  * it opens terminal windows over the user's work

Run it on mini instead — bin/remote-measure-others.sh explains how
(a GUI session is required; ssh cannot dispatch AppleEvents).

MARSPOT_MEASURE_ANYWHERE=1 overrides this, for when a rough local
reading is genuinely what you want.
WARN
  exit 2
fi



SCENARIOS=(cat-ascii cat-mixed cat-cjk cat-emoji)
# terminal.app is the OS-vendor reference floor — ships with macOS, no
# downloads, defines the bar marspot needs to clear. iterm2 / warp /
# ghostty are the real competitors. All four driven by the same
# paste-and-wait protocol; for fully-automated runs see
# bin/drivers/<term>.sh.
OTHER_TERMINALS=(terminal iterm warp ghostty)

PRINT_ONLY=0
for arg in "${@:-}"; do
  case "$arg" in
    --print-only) PRINT_ONLY=1 ;;
  esac
done

# Number of timed trials per (terminal, scenario).  Median is taken over
# these so single-shot variance can't shift the verdict (perf-attack E5).
TRIALS=${TRIALS:-3}

# E4: stale-marker cleanup.  Pre-existing /tmp/measure-{terminal}-all.txt
# files from earlier runs that still contain ==ALL_DONE== would be
# picked up immediately by the polling loop, polluting fresh data.
# Remove them up front; the build_command's `rm -f $marker` provides a
# second line of defence at paste time.
for t in "${OTHER_TERMINALS[@]}"; do
  rm -f "/tmp/measure-${t}-all.txt"
done

build_command() {
  # The whole matrix now lives in a script file generated by
  # write_live_matrix_script (bin/_lib.sh), and every terminal is
  # handed the same path to run.  Two reasons this replaced the
  # multi-KB one-liner this function used to echo:
  #
  #   - identical work.  The terminals are driven four different ways
  #     (AppleScript, System Events keystrokes, `-e`, a wrapper script);
  #     a shared file is the only way to be sure they execute the same
  #     bytes.
  #   - the trial now ends with a DSR round-trip, and quoting an escape
  #     sequence through AppleScript `write text` inside a shell string
  #     is a losing game.
  #
  # The DSR is what makes the number mean anything: `cat` returning
  # proves only that the bytes reached the PTY, and a terminal that
  # drops under pressure finishes early and "wins".
  local marker=$1
  # Per terminal, not per process: all four used to share one path, so
  # writing the block for the next terminal overwrote the script the
  # previous one was told to run — every block ended up pointing at
  # whichever marker was generated last.  Pasting them one at a time by
  # hand hid it; driving them does not.
  local script="/tmp/marspot-live-matrix-$$-$(basename "$marker" .txt).sh"
  local paths=()
  local s
  for s in "${SCENARIOS[@]}"; do
    paths+=("$SCENARIOS_DIR/$s.bin")
  done
  write_live_matrix_script "$script" "$marker" "$TRIALS" "${paths[@]}"
  LAST_BUILT_SCRIPT="$script"
  echo "bash $script"
}


# Drive a terminal instead of asking a human to paste.
#
# The header above says AppleScript-driven benching is "too fragile";
# that verdict predates checking, and it was checked on 2026-09-07:
# a fresh iTerm2 window created, a command written into it and the
# whole buffer read back with select-all all worked first time.  So a
# terminal that can be driven is driven, and only one that cannot
# falls back to the paste block.
#
# Deliberately narrow: `write text` into a NEW window, nothing else.
# The failure mode is a marker that never appears, which the existing
# wait already handles by timing out.
# Close a window this script opened.  Whatever it opens, it closes —
# the numbers are gone the moment the marker is written, and leaving
# windows over someone's work is the same defect as leaving a dev
# marspot running.
close_driven_window() {
  case "$1" in
    iterm)
      osascript >/dev/null 2>&1 <<'OSA'
tell application "iTerm2"
  if (count of windows) > 0 then close (first window)
end tell
OSA
      ;;
    terminal)
      osascript >/dev/null 2>&1 <<'OSA'
tell application "Terminal"
  if (count of windows) > 0 then close (first window) saving no
end tell
OSA
      ;;
  esac
}

drive_terminal() {
  local term=$1 cmd=$2
  case "$term" in
    iterm)
      osascript >/dev/null 2>&1 <<OSA || return 1
tell application "iTerm2"
  activate
  set w to (create window with default profile)
  tell current session of w to write text "$cmd"
end tell
OSA
      ;;
    terminal)
      osascript >/dev/null 2>&1 <<OSA || return 1
tell application "Terminal"
  activate
  do script "$cmd"
end tell
OSA
      ;;
    *) return 1 ;;
  esac
  return 0
}

# Is this terminal installed at all?  Measuring one that is not wastes
# the whole 600 s wait on a marker nobody will ever write.
terminal_installed() {
  case "$1" in
    iterm)    [[ -d /Applications/iTerm.app ]] ;;
    terminal) [[ -d /System/Applications/Utilities/Terminal.app || -d /Applications/Utilities/Terminal.app ]] ;;
    warp)     [[ -d /Applications/Warp.app ]] ;;
    ghostty)  [[ -d /Applications/Ghostty.app ]] ;;
    *) return 1 ;;
  esac
}

print_paste_block() {
  local term=$1
  local marker="/tmp/measure-${term}-all.txt"
  echo
  echo "----------------------------------------------------------------"
  echo "  $term — open a fresh window, paste, hit return:"
  echo "----------------------------------------------------------------"
  build_command "$marker"
  echo
}

wait_for_marker() {
  local marker=$1
  local timeout_s=${2:-300}
  local start
  start=$(date +%s)
  while true; do
    if [[ -s "$marker" ]] && grep -q "==ALL_DONE==" "$marker"; then
      return 0
    fi
    local now
    now=$(date +%s)
    if (( now - start > timeout_s )); then
      return 1
    fi
    sleep 1
  done
}

parse_marker() {
  # Walk a marker and emit `<scenario>:<median_ns>` per line, with the
  # median computed across however many trials the marker contains
  # for that scenario (perf-attack E5).  Format we wrote:
  #   ==SCN== cat-ascii
  #   real X.XX        <- trial 1
  #   user ...
  #   sys ...
  #   ==SCN== cat-ascii
  #   real Y.YY        <- trial 2
  #   ...
  local marker=$1
  awk '
    /^==SCN==/ { current = $2; certified = 0; next }
    # The trial writes `cpr=<row>,<col>` before time'"'"'s output.  Empty
    # (`cpr=,`) means the DSR read timed out — the terminal never
    # confirmed it consumed the corpus, so the elapsed time measures
    # the PTY buffer, not the terminal.  Drop it.
    /^cpr=/ { certified = ($0 ~ /^cpr=[0-9]/); next }
    /^real/ {
      if (!certified) { next }
      certified = 0
      s = $2
      if (s ~ /m/) {
        split(s, parts, "m")
        mins = parts[1]+0
        sub("s", "", parts[2])
        secs = parts[2]+0
        total = mins*60 + secs
      } else {
        total = s+0
      }
      ns = total * 1e9
      n[current]++
      samples[current, n[current]] = ns
      # Preserve scenario order as first encountered.
      if (!(current in seen)) {
        seen[current] = 1
        order[++ocount] = current
      }
    }
    END {
      for (oi = 1; oi <= ocount; oi++) {
        k = order[oi]
        cnt = n[k]
        for (i = 1; i <= cnt; i++) v[i] = samples[k, i]
        # In-place insertion sort (cnt is small, typically 3).
        for (i = 2; i <= cnt; i++) {
          key = v[i]; j = i - 1
          while (j >= 1 && v[j] > key) { v[j+1] = v[j]; j-- }
          v[j+1] = key
        }
        mid = int((cnt + 1) / 2)
        printf "%s:%d\n", k, v[mid]
      }
    }
  ' "$marker"
}

# ---- main ----------------------------------------------------------------

for s in "${SCENARIOS[@]}"; do
  if [[ ! -f "$SCENARIOS_DIR/$s.bin" ]]; then
    echo "missing $SCENARIOS_DIR/$s.bin — run bin/gen-scenarios.sh first" >&2
    exit 2
  fi
done

for t in "${OTHER_TERMINALS[@]}"; do
  print_paste_block "$t"
done

if [[ $PRINT_ONLY -eq 1 ]]; then
  exit 0
fi

echo "----------------------------------------------------------------"
echo "Waiting for markers (Ctrl-C to abort).  Each window finishes when"
echo "you see all 4 scenario outputs scroll past."
echo "----------------------------------------------------------------"

OUT_JSON="$RESULTS_DIR/cross-terminal-other.json"
echo "{" > "$OUT_JSON"
first=1
for t in "${OTHER_TERMINALS[@]}"; do
  marker="/tmp/measure-${t}-all.txt"
  if ! terminal_installed "$t"; then
    echo "==> $t is not installed — skipped"
    continue
  fi
  build_command "$marker" >/dev/null
  DROVE=""
  if drive_terminal "$t" "bash $LAST_BUILT_SCRIPT"; then
    echo "==> $t driven automatically"
    DROVE=1
  fi
  echo "==> waiting on $marker"
  if wait_for_marker "$marker" 600; then
    echo "    done"
    [[ -n "${DROVE:-}" ]] && close_driven_window "$t"
    [[ $first -eq 0 ]] && echo "," >> "$OUT_JSON"
    first=0
    printf '  "%s": {' "$t" >> "$OUT_JSON"
    inner=1
    while IFS=":" read -r scenario ns; do
      [[ -z "$scenario" ]] && continue
      # Bytes actually pushed: file size x live repeat count.
      bytes=$(( $(stat -f%z "$SCENARIOS_DIR/$scenario.bin") \
                * $(live_repeat "$SCENARIOS_DIR/$scenario.bin") ))
      bps=$(( bytes * 1000000000 / ns ))
      mb=$(echo "scale=1; $bps/1048576" | bc)
      [[ $inner -eq 0 ]] && printf "," >> "$OUT_JSON"
      inner=0
      printf '"%s":{"median_ns":%s,"bytes_per_sec":%s}' "$scenario" "$ns" "$bps" >> "$OUT_JSON"
      printf "    %-12s %s ns  %s MB/s\n" "$scenario" "$ns" "$mb"
    done < <(parse_marker "$marker")
    printf '}' >> "$OUT_JSON"
  else
    echo "    timeout — skipping"
  fi
done
echo >> "$OUT_JSON"
echo "}" >> "$OUT_JSON"
echo
echo "==> $OUT_JSON"
/bin/cat "$OUT_JSON"
